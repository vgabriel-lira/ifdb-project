create table if not exists public.filmes (
  id bigint generated by default as identity primary key,
  titulo text not null,
  genero text,
  ano int,
  sinopse text,
  "imagemUrl" text,
  created_at timestamptz not null default now()
);

alter table public.filmes enable row level security;

drop policy if exists "filmes_select" on public.filmes;
drop policy if exists "filmes_insert" on public.filmes;
drop policy if exists "filmes_delete" on public.filmes;

create policy "filmes_select" on public.filmes
  for select to anon using (true);
create policy "filmes_insert" on public.filmes
  for insert to anon with check (true);
create policy "filmes_delete" on public.filmes
  for delete to anon using (true);

create table if not exists public.clientes (
  id bigint generated by default as identity primary key,
  nome text not null,
  email text not null unique,
  senha text not null,
  created_at timestamptz not null default now()
);

alter table public.clientes enable row level security;

drop policy if exists "clientes_select" on public.clientes;
drop policy if exists "clientes_insert" on public.clientes;

create policy "clientes_select" on public.clientes
  for select to anon using (true);
create policy "clientes_insert" on public.clientes
  for insert to anon with check (true);
